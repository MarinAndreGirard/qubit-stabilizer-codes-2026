#!/usr/bin/env python3
"""Check that every code in codes/codes.csv is pure. Plain Python 3.8+, no packages.

A stabilizer code of distance d is pure if its stabilizer group S has no non-identity element of weight
below d. Then the whole normalizer N(S), and not only N(S) minus S, has no non-identity element of weight
below d, and all Pauli operators of weight at most (d-1)/2 have distinct syndromes.

Method (a Brouwer-Zimmermann lower bound on the minimum weight of S, for additive codes):

  Write each generator as a binary vector of length 3n, (x | z | x+z). A Pauli operator of weight w has
  binary weight exactly 2w in this form.

  An information set is a set of r = n-k columns on which the generators have full rank. The program finds
  disjoint information sets I_1, I_2, ... greedily, and for each one a basis M_i of S that is the identity
  on I_i. The last set may have rank r - delta < r.

  Every non-identity element of S is a sum of some rows of M_i, for each i. If it uses at least j+1 rows of
  every M_i, its binary weight is at least B_j = sum_i max(0, j+1-delta_i), because the sets are disjoint,
  so its Pauli weight is at least ceil(B_j / 2). The program takes the smallest j with ceil(B_j / 2) >= d
  and enumerates every sum of 1..j rows of every M_i. The code is pure iff none of them has weight below d.

Usage:  python3 verify/check_purity.py            (all codes; writes verify/results/purity.csv)
        python3 verify/check_purity.py --selftest  (compare with brute force on small random groups)
"""
import csv, os, random, sys, time
from math import comb

HERE = os.path.dirname(os.path.abspath(__file__))
REL = os.path.join(HERE, '..')

if hasattr(int, 'bit_count'):
    def popcount(v):
        return v.bit_count()
else:
    def popcount(v):
        return bin(v).count('1')


def load(path):
    rows, n = [], None
    for line in open(path):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        x, z = line.split('|')
        n = len(x)
        rows.append((int(x[::-1], 2), int(z[::-1], 2)))
    return rows, n


def information_sets(rows3, ncols):
    """Disjoint information sets, greedily. Returns [(basis M_i, delta_i)]; the rows of M_i with a pivot
    are the identity on the pivot columns of set i."""
    r, used, sets = len(rows3), 0, []
    while True:
        M, npiv = list(rows3), 0
        pivots = []
        for c in range(ncols):
            if (used >> c) & 1:
                continue
            bit = 1 << c
            t = next((i for i in range(npiv, r) if M[i] & bit), None)
            if t is None:
                continue
            M[npiv], M[t] = M[t], M[npiv]
            for i in range(r):
                if i != npiv and M[i] & bit:
                    M[i] ^= M[npiv]
            pivots.append(c)
            npiv += 1
            if npiv == r:
                break
        if not pivots:
            break
        for c in pivots:
            used |= 1 << c
        sets.append((M, r - npiv))
        if npiv < r:
            break
    return sets


def light_word(M, j, thr):
    """A sum of 1..j rows of M with binary weight below thr, or None."""
    r = len(M)

    def rec(start, acc, left):
        if left == 1:
            for t in range(start, r):
                if popcount(acc ^ M[t]) < thr:
                    return acc ^ M[t]
            return None
        for t in range(start, r):
            v = acc ^ M[t]
            if popcount(v) < thr:
                return v
            w = rec(t + 1, v, left - 1)
            if w is not None:
                return w
        return None

    return rec(0, 0, j) if j >= 1 else None


def stabilizer_min_weight_at_least(rows, n, D):
    """True iff every non-identity element of the group generated by rows (pairs of x, z bit masks) has
    Pauli weight at least D. Also returns the details of the computation."""
    rows3 = [x | (z << n) | ((x ^ z) << (2 * n)) for x, z in rows]
    r = len(rows3)
    sets = information_sets(rows3, 3 * n)
    deltas = [dl for _, dl in sets]
    j = 0
    while j < r and (sum(max(0, j + 1 - dl) for dl in deltas) + 1) // 2 < D:
        j += 1                                    # at j = r every element is enumerated and the test is exact
    nodes = len(sets) * sum(comb(r, i) for i in range(1, j + 1))
    found = None
    for M, _ in sets:
        found = light_word(M, j, 2 * D)
        if found is not None:
            break
    info = dict(information_sets=len(sets), last_set_rank_deficit=deltas[-1], depth_j=j, sums_enumerated=nodes,
                bound_on_other_elements=(sum(max(0, j + 1 - dl) for dl in deltas) + 1) // 2,
                light_element_weight=popcount(found) // 2 if found is not None else '')
    return found is None, info


def selftest(trials=400, seed=1):
    rng = random.Random(seed)
    for trial in range(trials):
        n = rng.randint(3, 9)
        r = rng.randint(1, min(2 * n, 9))
        rows = []
        while len(rows) < r:                      # independent generators, sometimes with light elements
            w = rng.randint(1, n)
            sup = rng.sample(range(n), w if rng.random() < 0.3 else n)
            x = sum(rng.getrandbits(1) << q for q in sup)
            z = sum(rng.getrandbits(1) << q for q in sup)
            cand = rows + [(x, z)]
            vecs = [a | (b << n) for a, b in cand]
            rank, vv = 0, list(vecs)
            for c in range(2 * n):
                p = next((i for i in range(rank, len(vv)) if (vv[i] >> c) & 1), None)
                if p is None:
                    continue
                vv[rank], vv[p] = vv[p], vv[rank]
                for i in range(len(vv)):
                    if i != rank and (vv[i] >> c) & 1:
                        vv[i] ^= vv[rank]
                rank += 1
            if rank == len(cand):
                rows = cand
        best = n + 1
        for mask in range(1, 1 << r):
            x = z = 0
            for i in range(r):
                if (mask >> i) & 1:
                    x ^= rows[i][0]
                    z ^= rows[i][1]
            best = min(best, popcount(x | z))
        for D in range(1, n + 2):
            ok, info = stabilizer_min_weight_at_least(rows, n, D)
            assert ok == (best >= D), (trial, n, r, D, best, info)
    print(f'selftest passed: {trials} random groups, every threshold agrees with brute force')


def main():
    if '--selftest' in sys.argv:
        return selftest()
    out, impure = [], []
    for c in csv.DictReader(open(os.path.join(REL, 'codes', 'codes.csv'))):
        n, k, d = int(c['n']), int(c['k']), int(c['d'])
        rows, nn = load(os.path.join(REL, 'codes', c['stabilizer_file']))
        assert nn == n and len(rows) == n - k
        t0 = time.time()
        ok, info = stabilizer_min_weight_at_least(rows, n, d)
        out.append(dict(id=c['id'], n=n, k=k, d=d, pure=ok, **info, seconds=round(time.time() - t0, 2)))
        if not ok:
            impure.append(c['id'])
        print(f"[[{n},{k},{d}]] {c['id']}: {'pure' if ok else 'NOT PURE'}  (depth {info['depth_j']}, "
              f"{info['sums_enumerated']} sums, {out[-1]['seconds']} s)", flush=True)
    path = os.path.join(HERE, 'results', 'purity.csv')
    with open(path, 'w', newline='') as f:
        w = csv.DictWriter(f, list(out[0]))
        w.writeheader()
        w.writerows(out)
    print(f'{len(out) - len(impure)} of {len(out)} codes are pure; not pure: {impure}')


if __name__ == '__main__':
    main()
